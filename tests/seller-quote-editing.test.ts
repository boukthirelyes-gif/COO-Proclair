import test from 'node:test';
import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {readFile,readdir} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {PrismaClient} from '@prisma/client';
import {PrismaPg} from '@prisma/adapter-pg';
import {presets,userActor} from '../src/lib/access';
import {LeadService} from '../src/sales/leads';
import {SellerQuotes} from '../src/sales/seller-quotes';
const {Client}=createRequire(import.meta.url)('pg');
test('personal draft corrections recalculate cents, enforce current ownership and serialize issuance',{skip:!process.env.TEST_DATABASE_URL,timeout:60000},async()=>{
 const database=process.env.TEST_DATABASE_URL!,schema='quoteedit_'+randomUUID().replaceAll('-',''),setup=new Client({connectionString:database});
 await setup.connect();await setup.query(`CREATE SCHEMA "${schema}"`);await setup.query(`SET search_path TO "${schema}"`);
 const db=new PrismaClient({adapter:new PrismaPg({connectionString:database},{schema})});
 try{
  for(const e of (await readdir('prisma/migrations',{withFileTypes:true})).filter(e=>e.isDirectory()).sort((a,b)=>a.name.localeCompare(b.name)))await setup.query(await readFile(`prisma/migrations/${e.name}/migration.sql`,'utf8'));
  const one=await db.appUser.create({data:{username:'one',name:'One',role:'SELLER',permissions:presets.SELLER,passwordHash:'unused-fixture'}}),two=await db.appUser.create({data:{username:'two',name:'Two',role:'SELLER',permissions:presets.SELLER,passwordHash:'unused-fixture'}}),actor=userActor(one),other=userActor(two),quotes=new SellerQuotes(db);
  await db.businessProfile.create({data:{id:'proclair',legalName:'Synthetic issuer'}});
  const lead=await new LeadService(db).create({name:'Draft buyer',address:'Synthetic address',pipelineId:'proclair-sales',stageId:'proclair-qualify',idempotencyKey:'edit-lead-fixture'},actor);
  const initial={leadId:lead.id,expectedLeadVersion:1,approved:true,validUntil:'2027-01-01',items:[{description:'Initial',quantity:1,unitPriceCents:10000}],idempotencyKey:'edit-quote-fixture'},created=await quotes.create(initial,actor);
  const edit={expectedVersion:1,validUntil:'2027-02-01',items:[{description:'Corrected',quantity:2,unitPriceCents:23999,taxRateBps:1497.5}]};
  await assert.rejects(()=>quotes.edit(created.id,edit,other),{code:'NOT_FOUND'});
  await assert.rejects(()=>quotes.edit(created.id,edit,{...actor,permissions:actor.permissions.filter(p=>p!=='sales.write')}),{code:'FORBIDDEN'});
  await assert.rejects(()=>quotes.edit(created.id,{...edit,customerId:'foreign'},actor));
  await assert.rejects(()=>quotes.edit(created.id,{...edit,validUntil:'2027-02-30'},actor));
  await assert.rejects(()=>quotes.edit(created.id,{...edit,items:[{...edit.items[0],unitPriceCents:1.5}]},actor));
  await db.lead.update({where:{id:lead.id},data:{status:'DO_NOT_CONTACT'}});
  await assert.rejects(()=>quotes.edit(created.id,edit,actor),{code:'DO_NOT_CONTACT'});
  await db.lead.update({where:{id:lead.id},data:{status:'CONVERTED'}});
  const competing=await Promise.allSettled([quotes.edit(created.id,edit,actor),quotes.edit(created.id,edit,actor)]);
  assert.equal(competing.filter(r=>r.status==='fulfilled').length,1);
  assert.equal((competing.find(r=>r.status==='rejected') as PromiseRejectedResult).reason.code,'VERSION_CONFLICT');
  const row=await db.quote.findUniqueOrThrow({where:{id:created.id}});
  assert.equal(row.version,2);assert.equal(row.subtotalCents,47998);assert.equal(row.taxCents,7188);assert.equal(row.totalCents,55186);assert.equal(row.validUntil,'2027-02-01');assert.equal(row.status,'DRAFT');assert.equal(row.number,null);
  assert.equal((await quotes.create(initial,actor)).replayed,true);
  assert.equal(await db.customer.count(),1);assert.equal(await db.clientLink.count(),0);
  await db.lead.update({where:{id:lead.id},data:{ownerId:other.id}});
  await assert.rejects(()=>quotes.edit(created.id,{...edit,expectedVersion:2},actor),{code:'NOT_FOUND'});
  await assert.rejects(()=>quotes.edit(created.id,{...edit,expectedVersion:2},other),{code:'NOT_FOUND'});
  await db.lead.update({where:{id:lead.id},data:{ownerId:actor.id}});
  const race=await Promise.allSettled([quotes.edit(created.id,{...edit,expectedVersion:2},actor),quotes.issue(created.id,{expectedVersion:2},actor)]);
  assert.equal(race.filter(r=>r.status==='fulfilled').length,1);
  const latest=await db.quote.findUniqueOrThrow({where:{id:created.id}});
  if(latest.status==='DRAFT')await quotes.issue(created.id,{expectedVersion:latest.version},actor);
  const issued=await db.quote.findUniqueOrThrow({where:{id:created.id}});
  await assert.rejects(()=>quotes.edit(created.id,{...edit,expectedVersion:issued.version},actor),{code:'IMMUTABLE_QUOTE'});
  assert.equal(await db.invoice.count(),0);assert.equal(await db.payment.count(),0);assert.equal(await db.visit.count(),0);
  assert.ok(await db.auditEvent.findFirst({where:{action:'SELLER_QUOTE_UPDATED',entityId:created.id}}));
 }finally{await db.$disconnect();await setup.query(`DROP SCHEMA "${schema}" CASCADE`);await setup.end()}
});
