CREATE TABLE "AppUser" (
 "id" TEXT PRIMARY KEY, "username" TEXT NOT NULL UNIQUE, "name" TEXT NOT NULL,
 "passwordHash" TEXT NOT NULL, "role" TEXT NOT NULL CHECK ("role" IN ('ADMIN','MANAGER','DISPATCHER','SELLER','VIEWER')),
 "permissions" TEXT[] NOT NULL, "active" BOOLEAN NOT NULL DEFAULT TRUE,
 "version" INTEGER NOT NULL DEFAULT 1, "sessionVersion" INTEGER NOT NULL DEFAULT 1,
 "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE "ProspectPin" (
 "id" TEXT PRIMARY KEY, "address" TEXT NOT NULL,
 "latitude" DOUBLE PRECISION NOT NULL CHECK ("latitude" BETWEEN -90 AND 90),
 "longitude" DOUBLE PRECISION NOT NULL CHECK ("longitude" BETWEEN -180 AND 180),
 "status" TEXT NOT NULL DEFAULT 'NOT_KNOCKED' CHECK ("status" IN ('SOLD','NO_HOME','NOT_INTERESTED','CALLBACK','NOT_KNOCKED','FOLLOW_UP','ACTIVE','CANCELLED','DO_NOT_CONTACT')),
 "notes" TEXT NOT NULL DEFAULT '', "callbackAt" TIMESTAMP(3),
 "ownerId" TEXT REFERENCES "AppUser"("id"), "createdBy" TEXT NOT NULL,
 "version" INTEGER NOT NULL DEFAULT 1, "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
 "updatedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX "ProspectPin_ownerId_status_idx" ON "ProspectPin"("ownerId","status");
